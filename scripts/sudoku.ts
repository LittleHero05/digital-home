// Generates a year of daily sudoku puzzles and writes them to content/sudoku.ts.
// Run with: node scripts/sudoku.ts   (Node 23+ runs TypeScript directly)
//
// Every puzzle is our own (no third-party puzzles) and has exactly one solution.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { countSolutions, gridToString, search, type Grid } from "../lib/sudoku.ts";

const COUNT = 365;
const GIVENS = 36; // "easy": stop removing numbers once this many are left
const START_DATE = "2026-10-01"; // puzzle no. 001
const SEED = 20261001;

// Small seeded random generator, so the same puzzles come out every run.
function mulberry32(seed: number) {
  let state = seed;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const random = mulberry32(SEED);
const shuffle = <T>(items: T[]): T[] => {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
};

function makePuzzle(): string {
  const solution: Grid = Array(81).fill(0);
  search(solution, 1, shuffle);

  const puzzle = [...solution];
  let givens = 81;
  // Remove numbers in pairs that mirror through the centre, so puzzles look balanced.
  for (const cell of shuffle(Array.from({ length: 41 }, (_, i) => i))) {
    if (givens <= GIVENS) break;
    const twin = 80 - cell;
    const kept = [puzzle[cell], puzzle[twin]];
    puzzle[cell] = 0;
    puzzle[twin] = 0;
    if (countSolutions(puzzle) === 1) {
      givens -= cell === twin ? 1 : 2;
    } else {
      puzzle[cell] = kept[0];
      puzzle[twin] = kept[1];
    }
  }
  return gridToString(puzzle);
}

const puzzles: string[] = [];
const seen = new Set<string>();
while (puzzles.length < COUNT) {
  const puzzle = makePuzzle();
  if (seen.has(puzzle)) continue;
  seen.add(puzzle);
  puzzles.push(puzzle);
}

const file = `// Generated by scripts/sudoku.ts. Do not edit by hand; re-run the script instead.
// One puzzle per day starting on sudokuStartDate; "." is an empty square.

export const sudokuStartDate = "${START_DATE}";
export const sudokuDifficulty = "easy";

export const puzzles: string[] = [
${puzzles.map((p) => `  "${p}",`).join("\n")}
];
`;

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "content", "sudoku.ts");
writeFileSync(out, file);
const counts = puzzles.map((p) => [...p].filter((c) => c !== ".").length);
console.log(`wrote ${puzzles.length} puzzles to content/sudoku.ts (givens ${Math.min(...counts)}–${Math.max(...counts)})`);
